  static pw.Widget _buildSummaryBlock(String title, String value, PdfColor valueColor) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.center,
      children: [
        pw.Text(title, style: const pw.TextStyle(fontSize: 8.5, color: PdfColors.grey700)),
        pw.SizedBox(height: 4),
        pw.Text(value, style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: valueColor)),
      ],
    );
  }

  /// Shares a report file via Android share sheet
  Future<void> shareReport(String filePath) async {
    final file = File(filePath);
    if (!await file.exists()) {
      throw FileSystemException('Report file does not exist at $filePath');
    }
    await Share.shareXFiles([XFile(filePath)], text: 'Money Manager Monthly Financial Report');
  }
