class MonthlyReportRecord {
  final int? id;
  final String reportType; // 'income_expense' | 'budget_performance'
  final String reportingMonth; // 'YYYY-MM'
  final DateTime generatedAt;
  final String filePath;
  final int fileSizeBytes;
  final String checksum;
  final bool isAutoGenerated;

  const MonthlyReportRecord({
    this.id,
    required this.reportType,
    required this.reportingMonth,
    required this.generatedAt,
    required this.filePath,
    required this.fileSizeBytes,
    required this.checksum,
    this.isAutoGenerated = true,
  });

  Map<String, dynamic> toMap() {
    return {
      if (id != null) 'id': id,
      'report_type': reportType,
      'reporting_month': reportingMonth,
      'generated_at': generatedAt.toIso8601String(),
      'file_path': filePath,
      'file_size_bytes': fileSizeBytes,
      'checksum': checksum,
      'is_auto_generated': isAutoGenerated ? 1 : 0,
    };
  }

  factory MonthlyReportRecord.fromMap(Map<String, dynamic> map) {
    return MonthlyReportRecord(
      id: map['id'] as int?,
      reportType: map['report_type'] as String,
      reportingMonth: map['reporting_month'] as String,
      generatedAt: DateTime.parse(map['generated_at'] as String),
      filePath: map['file_path'] as String,
      fileSizeBytes: map['file_size_bytes'] as int,
      checksum: map['checksum'] as String,
      isAutoGenerated: (map['is_auto_generated'] as int? ?? 1) == 1,
    );
  }
}

class MonthlyPdfReportService {
  static final MonthlyPdfReportService instance = MonthlyPdfReportService._();
  MonthlyPdfReportService._();

  /// Directory where monthly PDF reports are stored
  Future<Directory> _getReportsDirectory() async {
    final appDir = await getApplicationDocumentsDirectory();
    final reportsDir = Directory('${appDir.path}/reports/monthly');
    if (!await reportsDir.exists()) {
      await reportsDir.create(recursive: true);
    }
    return reportsDir;
  }

  /// Calculates SHA-256 checksum of raw bytes
  static String calculateChecksum(Uint8List bytes) {
    return sha256.convert(bytes).toString();
  }

  /// Queries all generated reports from report_history table
  Future<List<MonthlyReportRecord>> getReportHistory() async {
    final db = await AppDatabase.instance.database;
    final rows = await db.query('report_history', orderBy: 'reporting_month DESC, generated_at DESC');
    return rows.map((r) => MonthlyReportRecord.fromMap(r)).toList();
  }

  /// Queries a specific report by type and month
  Future<MonthlyReportRecord?> getReport(String reportType, String reportingMonth) async {
    final db = await AppDatabase.instance.database;
    final rows = await db.query(
      'report_history',
      where: 'report_type = ? AND reporting_month = ?',
      whereArgs: [reportType, reportingMonth],
      orderBy: 'generated_at DESC',
      limit: 1,
    );
    if (rows.isEmpty) return null;
    return MonthlyReportRecord.fromMap(rows.first);
  }

  /// Catch-up check on app launch: If current day >= 1 and reports for previous month are missing, generate them.
  Future<void> checkAndGeneratePreviousMonthReports() async {
    final now = DateTime.now();
    final prevMonthDate = DateTime(now.year, now.month - 1, 1);
    final prevMonthStr = DateFormat('yyyy-MM').format(prevMonthDate);

    final incExpReport = await getReport('income_expense', prevMonthStr);
    final budgetReport = await getReport('budget_performance', prevMonthStr);

    if (incExpReport == null || budgetReport == null) {
      await generateReportsForMonth(prevMonthStr, isAuto: true);
    }
  }

  /// Generates both reports for the given month (e.g. '2026-03').
  Future<List<MonthlyReportRecord>> generateReportsForMonth(
    String monthStr, {
    bool forceRegenerate = false,
    bool isAuto = false,
    String currency = 'INR',
  }) async {
    final db = await AppDatabase.instance.database;

    // Load data from DB
    final txRows = await db.query(
      'transaction_log',
      where: "strftime('%Y-%m', date) = ?",
      whereArgs: [monthStr],
      orderBy: 'date ASC',
    );
    final transactions = txRows.map((r) => Transaction.fromMap(r)).toList();

    final accRows = await db.query('account');
    final accounts = accRows.map((r) => Account.fromMap(r)).toList();

    final catRows = await db.query('category');
    final categories = catRows.map((r) => Category.fromMap(r)).toList();

    final budgetRows = await db.query('budget', where: 'month = ?', whereArgs: [monthStr]);
    final budgets = budgetRows.map((r) => Budget.fromMap(r)).toList();

    final reportsDir = await _getReportsDirectory();
    final generatedRecords = <MonthlyReportRecord>[];

    // 1. Generate Report 1: Monthly Income & Expense Analysis
    final incExpFileName = 'Money_Manager_Income_Expense_Report_$monthStr.pdf';
    final incExpFile = File('${reportsDir.path}/$incExpFileName');

    final existingIncExp = await getReport('income_expense', monthStr);
    if (existingIncExp == null || forceRegenerate || !await incExpFile.exists()) {
      final bytes = await buildIncomeExpenseReportPdf(
        monthStr: monthStr,
        transactions: transactions,
        accounts: accounts,
        categories: categories,
        currency: currency,
      );

      await incExpFile.writeAsBytes(bytes, flush: true);
      final checksum = calculateChecksum(bytes);

      final record = MonthlyReportRecord(
        reportType: 'income_expense',
        reportingMonth: monthStr,
        generatedAt: DateTime.now(),
        filePath: incExpFile.path,
        fileSizeBytes: bytes.length,
        checksum: checksum,
        isAutoGenerated: isAuto,
      );

      await db.insert('report_history', record.toMap());
      generatedRecords.add(record);
    } else {
      generatedRecords.add(existingIncExp);
    }

    // 2. Generate Report 2: Monthly Budget Performance Report
    final budgetFileName = 'Money_Manager_Budget_Report_$monthStr.pdf';
    final budgetFile = File('${reportsDir.path}/$budgetFileName');

    final existingBudget = await getReport('budget_performance', monthStr);
    if (existingBudget == null || forceRegenerate || !await budgetFile.exists()) {
      final bytes = await buildBudgetPerformanceReportPdf(
        monthStr: monthStr,
        transactions: transactions,
        budgets: budgets,
        categories: categories,
        currency: currency,
      );

      await budgetFile.writeAsBytes(bytes, flush: true);
      final checksum = calculateChecksum(bytes);

      final record = MonthlyReportRecord(
        reportType: 'budget_performance',
        reportingMonth: monthStr,
        generatedAt: DateTime.now(),
        filePath: budgetFile.path,
        fileSizeBytes: bytes.length,
        checksum: checksum,
        isAutoGenerated: isAuto,
      );

      await db.insert('report_history', record.toMap());
      generatedRecords.add(record);
    } else {
      generatedRecords.add(existingBudget);
    }

    // Trigger Notification
    await NotificationService.instance.showMonthlyReportAlert(monthStr);

    return generatedRecords;
  }

  /// Builds Report 1: Monthly Income & Expense Analysis PDF
  Future<Uint8List> buildIncomeExpenseReportPdf({
    required String monthStr,
    required List<Transaction> transactions,
    required List<Account> accounts,
    required List<Category> categories,
    required String currency,
  }) async {
    final pdf = pw.Document();
    final parts = monthStr.split('-');
    final year = int.tryParse(parts[0]) ?? DateTime.now().year;
    final month = int.tryParse(parts[1]) ?? DateTime.now().month;
    final monthName = DateFormat('MMMM yyyy').format(DateTime(year, month));

    final catMap = {for (var c in categories) c.id: c.name};
    final accMap = {for (var a in accounts) a.id: a.name};

    // Income & Expense totals (Exact minor arithmetic)
    int totalIncomeMinor = 0;
    int totalExpenseMinor = 0;
    int incomeCount = 0;
    int expenseCount = 0;

    final Map<int, int> incomeByCatMinor = {};
    final Map<int, int> incomeByCatCount = {};
    final Map<int, int> incomeByAccMinor = {};

    final Map<int, int> expenseByCatMinor = {};
    final Map<int, int> expenseByCatCount = {};

    final List<Transaction> expenseTxs = [];

    for (var tx in transactions) {
      if (tx.type == 'income') {
        totalIncomeMinor += tx.amountMinorUnits;
        incomeCount++;
        incomeByCatMinor[tx.categoryId] = (incomeByCatMinor[tx.categoryId] ?? 0) + tx.amountMinorUnits;
        incomeByCatCount[tx.categoryId] = (incomeByCatCount[tx.categoryId] ?? 0) + 1;
        incomeByAccMinor[tx.accountId] = (incomeByAccMinor[tx.accountId] ?? 0) + tx.amountMinorUnits;
      } else if (tx.type == 'expense') {
        totalExpenseMinor += tx.amountMinorUnits;
        expenseCount++;
        expenseByCatMinor[tx.categoryId] = (expenseByCatMinor[tx.categoryId] ?? 0) + tx.amountMinorUnits;
        expenseByCatCount[tx.categoryId] = (expenseByCatCount[tx.categoryId] ?? 0) + 1;
        expenseTxs.add(tx);
      }
    }

    final double totalIncome = totalIncomeMinor / 100.0;
    final double totalExpense = totalExpenseMinor / 100.0;
    final double netSavings = (totalIncomeMinor - totalExpenseMinor) / 100.0;
    final double savingsRate = totalIncome > 0 ? (netSavings / totalIncome) * 100.0 : 0.0;

    // Top 5 Expenses
    expenseTxs.sort((a, b) => b.amountMinorUnits.compareTo(a.amountMinorUnits));
    final top5Expenses = expenseTxs.take(5).toList();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          // 1. Header
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('MONEY MANAGER', style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
                  pw.Text('Monthly Income & Expense Analysis', style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: PdfColors.grey800)),
                  pw.Text('Period: $monthName', style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700)),
                ],
              ),
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.end,
                children: [
                  pw.Text('Currency: $currency', style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold)),
                  pw.Text('Generated: ${DateFormat('yyyy-MM-dd HH:mm').format(DateTime.now())}', style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
                  pw.Text('Status: Verified Production Report', style: const pw.TextStyle(fontSize: 8, color: PdfColors.green800)),
                ],
              ),
            ],
          ),
          pw.Divider(thickness: 1.5, color: PdfColors.red900),
          pw.SizedBox(height: 12),

          // 2. Executive Summary
          pw.Text('1. Executive Financial Summary', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.Container(
            padding: const pw.EdgeInsets.all(10),
            decoration: pw.BoxDecoration(
              color: PdfColors.grey100,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
              children: [
                _buildSummaryBlock('Total Income ($incomeCount)', CurrencyFormatter.format(totalIncome, currency), PdfColors.green800),
                _buildSummaryBlock('Total Expenses ($expenseCount)', CurrencyFormatter.format(totalExpense, currency), PdfColors.red800),
                _buildSummaryBlock('Net Savings', CurrencyFormatter.format(netSavings, currency), netSavings >= 0 ? PdfColors.green800 : PdfColors.red800),
                _buildSummaryBlock('Savings Rate', '${savingsRate.toStringAsFixed(1)}%', savingsRate >= 20 ? PdfColors.green800 : PdfColors.orange800),
              ],
            ),
          ),
          pw.SizedBox(height: 16),

          // 3. Income Analysis
          pw.Text('2. Income Breakdown by Category & Account', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.TableHelper.fromTextArray(
            headers: ['Category', 'Transactions', 'Amount', '% of Income'],
            data: incomeByCatMinor.entries.map((e) {
              final catName = catMap[e.key] ?? 'Uncategorized';
              final amt = e.value / 100.0;
              final pct = totalIncome > 0 ? (amt / totalIncome) * 100.0 : 0.0;
              return [catName, '${incomeByCatCount[e.key]}', CurrencyFormatter.format(amt, currency), '${pct.toStringAsFixed(1)}%'];
            }).toList(),
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9, color: PdfColors.white),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.green800),
            cellStyle: const pw.TextStyle(fontSize: 8.5),
            cellAlignment: pw.Alignment.centerLeft,
            cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
          ),
          pw.SizedBox(height: 16),

          // 4. Expense Analysis
          pw.Text('3. Expense Breakdown by Category', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.TableHelper.fromTextArray(
            headers: ['Category', 'Transactions', 'Amount', '% of Expenses'],
            data: expenseByCatMinor.entries.map((e) {
              final catName = catMap[e.key] ?? 'Uncategorized';
              final amt = e.value / 100.0;
              final pct = totalExpense > 0 ? (amt / totalExpense) * 100.0 : 0.0;
              return [catName, '${expenseByCatCount[e.key]}', CurrencyFormatter.format(amt, currency), '${pct.toStringAsFixed(1)}%'];
            }).toList(),
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9, color: PdfColors.white),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.red900),
            cellStyle: const pw.TextStyle(fontSize: 8.5),
            cellAlignment: pw.Alignment.centerLeft,
            cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
          ),
          pw.SizedBox(height: 16),

          // 5. Top 5 Expenses
          pw.Text('4. Top 5 Major Expenses', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.TableHelper.fromTextArray(
            headers: ['Date', 'Title', 'Category', 'Account', 'Amount'],
            data: top5Expenses.map((tx) {
              final catName = catMap[tx.categoryId] ?? 'Other';
              final accName = accMap[tx.accountId] ?? 'Account';
              return [
                DateFormat('yyyy-MM-dd').format(tx.date),
                tx.title,
                catName,
                accName,
                CurrencyFormatter.format(tx.amount, currency),
              ];
            }).toList(),
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9, color: PdfColors.white),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.grey800),
            cellStyle: const pw.TextStyle(fontSize: 8.5),
            cellAlignment: pw.Alignment.centerLeft,
            cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
          ),
          pw.SizedBox(height: 16),

          // 6. Account Summary
          pw.Text('5. Account Balances and Activity', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.TableHelper.fromTextArray(
            headers: ['Account Name', 'Type', 'Current Balance', 'Status'],
            data: accounts.map((acc) {
              return [
                acc.name,
                acc.type,
                CurrencyFormatter.format(acc.balance, currency),
                acc.isArchived ? 'Archived' : 'Active',
              ];
            }).toList(),
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9, color: PdfColors.white),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
            cellStyle: const pw.TextStyle(fontSize: 8.5),
            cellAlignment: pw.Alignment.centerLeft,
            cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
          ),
          pw.SizedBox(height: 16),

          // 7. Deterministic Financial Insights
          pw.Text('6. Observations & Recommendations', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.Bullet(
            text: savingsRate >= 20.0
                ? 'Strong Savings Rate: You saved ${savingsRate.toStringAsFixed(1)}% of your income this month, exceeding the 20% benchmark.'
                : 'Savings Alert: Your savings rate was ${savingsRate.toStringAsFixed(1)}%. Aim for 20% by curbing top discretionary expenses.',
            style: const pw.TextStyle(fontSize: 9),
          ),
          if (top5Expenses.isNotEmpty)
            pw.Bullet(
              text: 'Top Expense: "${top5Expenses.first.title}" accounted for ${CurrencyFormatter.format(top5Expenses.first.amount, currency)} (${totalExpense > 0 ? ((top5Expenses.first.amount / totalExpense) * 100).toStringAsFixed(1) : "0"}% of total outlays).',
              style: const pw.TextStyle(fontSize: 9),
            ),
          pw.Bullet(
            text: 'Financial Inflow vs Outflow: Total income of ${CurrencyFormatter.format(totalIncome, currency)} supported total spending of ${CurrencyFormatter.format(totalExpense, currency)}.',
            style: const pw.TextStyle(fontSize: 9),
          ),
        ],
      ),
    );

    return pdf.save();
  }

  /// Builds Report 2: Monthly Budget Performance Report PDF
  Future<Uint8List> buildBudgetPerformanceReportPdf({
    required String monthStr,
    required List<Transaction> transactions,
    required List<Budget> budgets,
    required List<Category> categories,
    required String currency,
  }) async {
    final pdf = pw.Document();
    final parts = monthStr.split('-');
    final year = int.tryParse(parts[0]) ?? DateTime.now().year;
    final month = int.tryParse(parts[1]) ?? DateTime.now().month;
    final monthName = DateFormat('MMMM yyyy').format(DateTime(year, month));

    final catMap = {for (var c in categories) c.id: c.name};

    // Filter ONLY budget-included expense transactions
    final budgetEligibleTxs = transactions.where((tx) => tx.type == 'expense' && tx.isBudgetIncluded).toList();

    // Spendings by category (minor units)
    final Map<int, int> spentByCatMinor = {};
    for (var tx in budgetEligibleTxs) {
      spentByCatMinor[tx.categoryId] = (spentByCatMinor[tx.categoryId] ?? 0) + tx.amountMinorUnits;
    }

    int totalPlannedMinor = 0;
    int totalSpentMinor = 0;

    for (var b in budgets) {
      totalPlannedMinor += b.limitAmountMinor;
      totalSpentMinor += (spentByCatMinor[b.categoryId] ?? 0);
    }

    final double totalPlanned = totalPlannedMinor / 100.0;
    final double totalSpent = totalSpentMinor / 100.0;
    final double variance = (totalPlannedMinor - totalSpentMinor) / 100.0;
    final double adherenceRate = totalPlanned > 0 ? (totalSpent / totalPlanned) * 100.0 : 0.0;

    // Daily breakdown & rollover analysis
    final dailySummary = DailySpendingCalculator.calculate(
      year: year,
      month: month,
      monthlyBudgetMinor: totalPlannedMinor,
      transactions: budgetEligibleTxs,
      referenceDate: DateTime(year, month + 1, 0),
    );

    int underDays = 0;
    int overDays = 0;
    int maxOverspendMinor = 0;
    DateTime? maxOverspendDate;

    for (var day in dailySummary.days) {
      if (day.status == 'under' || day.status == 'at') {
        underDays++;
      } else if (day.status == 'over') {
        overDays++;
        final overAmt = day.actualSpentMinor - day.availableMinor;
        if (overAmt > maxOverspendMinor) {
          maxOverspendMinor = overAmt;
          maxOverspendDate = day.date;
        }
      }
    }

    final double avgDailyAllowance = dailySummary.totalDays > 0 ? totalPlanned / dailySummary.totalDays : 0.0;
    final double avgDailySpend = dailySummary.totalDays > 0 ? totalSpent / dailySummary.totalDays : 0.0;

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (context) => [
          // Header
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('MONEY MANAGER', style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
                  pw.Text('Monthly Budget Performance & Rollover Report', style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: PdfColors.grey800)),
                  pw.Text('Period: $monthName', style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700)),
                ],
              ),
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.end,
                children: [
                  pw.Text('Currency: $currency', style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold)),
                  pw.Text('Generated: ${DateFormat('yyyy-MM-dd HH:mm').format(DateTime.now())}', style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
                  pw.Text('Audit Scope: Budget-Eligible Outlays Only', style: const pw.TextStyle(fontSize: 8, color: PdfColors.blueGrey800)),
                ],
              ),
            ],
          ),
          pw.Divider(thickness: 1.5, color: PdfColors.red900),
          pw.SizedBox(height: 12),

          // Budget Performance Summary
          pw.Text('1. Overall Budget Performance', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.Container(
            padding: const pw.EdgeInsets.all(10),
            decoration: pw.BoxDecoration(
              color: PdfColors.grey100,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
              children: [
                _buildSummaryBlock('Total Planned Budget', CurrencyFormatter.format(totalPlanned, currency), PdfColors.grey900),
                _buildSummaryBlock('Actual Spend', CurrencyFormatter.format(totalSpent, currency), variance >= 0 ? PdfColors.green800 : PdfColors.red800),
                _buildSummaryBlock('Variance', CurrencyFormatter.format(variance, currency), variance >= 0 ? PdfColors.green800 : PdfColors.red800),
                _buildSummaryBlock('Adherence Rate', '${adherenceRate.toStringAsFixed(1)}%', adherenceRate <= 100 ? PdfColors.green800 : PdfColors.red800),
                _buildSummaryBlock('Net Rollover', CurrencyFormatter.format(dailySummary.netRolloverBalance, currency), dailySummary.netRolloverBalanceMinor >= 0 ? PdfColors.green800 : PdfColors.red800),
              ],
            ),
          ),
          pw.SizedBox(height: 16),

          // Category-by-Category Table
          pw.Text('2. Category Budget Adherence Table', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
          pw.SizedBox(height: 6),
          pw.TableHelper.fromTextArray(
            headers: ['Category', 'Planned', 'Actual Spend', 'Variance', 'Status'],
            data: budgets.map((b) {
              final catName = catMap[b.categoryId] ?? 'Category';
              final spentMinor = spentByCatMinor[b.categoryId] ?? 0;
              final plannedMinor = b.limitAmountMinor;
              final varMinor = plannedMinor - spentMinor;

              final String status;
              if (spentMinor <= plannedMinor * 0.8) {
                status = 'Within Budget';
              } else if (spentMinor <= plannedMinor) {
                status = 'Near Limit';
              } else {
                status = 'Over Budget';
              }

              return [
                catName,
                CurrencyFormatter.format(b.limitAmount, currency),
                CurrencyFormatter.format(spentMinor / 100.0, currency),
                CurrencyFormatter.format(varMinor / 100.0, currency),
                status,
              ];
            }).toList(),
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9, color: PdfColors.white),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.red900),
            cellStyle: const pw.TextStyle(fontSize: 8.5),
            cellAlignment: pw.Alignment.centerLeft,
            cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
          ),
          pw.SizedBox(height: 16),

          // Daily Rollover & Calendar Performance
